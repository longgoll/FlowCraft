import type { TraceRecord, SpanData, SpanKind } from './types.js';

const SPAN_KIND_OTEL_MAP: Record<SpanKind, number> = {
  INTERNAL: 1,
  SERVER: 2,
  CLIENT: 3,
  PRODUCER: 4,
  CONSUMER: 5,
};

function formatOtelAttributeValue(value: unknown): Record<string, unknown> {
  if (typeof value === 'string') return { stringValue: value };
  if (typeof value === 'boolean') return { boolValue: value };
  if (typeof value === 'number') {
    return Number.isInteger(value) ? { intValue: value.toString() } : { doubleValue: value };
  }
  return { stringValue: JSON.stringify(value) };
}

function convertAttributesToOtel(attributes: Record<string, unknown> = {}) {
  return Object.entries(attributes).map(([key, val]) => ({
    key,
    value: formatOtelAttributeValue(val),
  }));
}

/**
 * Xuất TraceRecord sang định dạng OpenTelemetry ResourceSpans (OTLP JSON 1.0+)
 */
export function toOpenTelemetryResourceSpans(trace: TraceRecord) {
  const serviceName = trace.serviceName || 'unknown-service';

  const otelSpans = trace.spans.map((span) => {
    const startNano = BigInt(Math.floor(span.startTime)) * 1000000n;
    const endNano = BigInt(Math.floor(span.endTime || span.startTime + (span.durationMs || 0))) * 1000000n;

    return {
      traceId: span.traceId,
      spanId: span.spanId,
      parentSpanId: span.parentSpanId || undefined,
      name: span.name,
      kind: SPAN_KIND_OTEL_MAP[span.kind] || 1,
      startTimeUnixNano: startNano.toString(),
      endTimeUnixNano: endNano.toString(),
      attributes: convertAttributesToOtel({
        ...span.attributes,
        'service.name': span.serviceName || serviceName,
        'tracelens.duration_ms': span.durationMs,
      }),
      status: {
        code: span.status.code === 'ERROR' ? 2 : span.status.code === 'OK' ? 1 : 0,
        message: span.status.message,
      },
    };
  });

  return {
    resourceSpans: [
      {
        resource: {
          attributes: [
            { key: 'service.name', value: { stringValue: serviceName } },
            { key: 'telemetry.sdk.name', value: { stringValue: 'tracelens' } },
            { key: 'telemetry.sdk.language', value: { stringValue: 'nodejs' } },
            { key: 'telemetry.sdk.version', value: { stringValue: '0.1.0' } },
          ],
        },
        scopeSpans: [
          {
            scope: {
              name: '@tracelens/exporter',
              version: '0.1.0',
            },
            spans: otelSpans,
          },
        ],
      },
    ],
  };
}

/**
 * Xuất TraceRecord sang định dạng HAR 1.2 (HTTP Archive)
 * Tương thích để import vào Chrome DevTools, Postman, Insomnia, Charles Proxy
 */
export function toHar(trace: TraceRecord) {
  const http = trace.http;
  const startedDateTime = new Date(trace.timestamp).toISOString();
  const time = trace.durationMs;

  const headers = Object.entries(http?.headers || {}).map(([name, value]) => ({
    name,
    value: String(value),
  }));

  const queryString = Object.entries(http?.query || {}).map(([name, value]) => ({
    name,
    value: String(value),
  }));

  const entries = [
    {
      pageref: `page_${trace.id}`,
      startedDateTime,
      time,
      request: {
        method: http?.method || 'GET',
        url: http?.url || `http://localhost${http?.path || '/'}`,
        httpVersion: 'HTTP/1.1',
        cookies: [],
        headers,
        queryString,
        postData: http?.body
          ? {
              mimeType: 'application/json',
              text: typeof http.body === 'string' ? http.body : JSON.stringify(http.body),
            }
          : undefined,
        headersSize: -1,
        bodySize: -1,
      },
      response: {
        status: http?.statusCode || 200,
        statusText: http?.statusCode === 200 ? 'OK' : http?.statusCode === 201 ? 'Created' : 'Custom',
        httpVersion: 'HTTP/1.1',
        cookies: [],
        headers: [
          { name: 'X-TraceLens-Trace-Id', value: trace.id },
          { name: 'Content-Type', value: 'application/json' },
        ],
        content: {
          size: -1,
          mimeType: 'application/json',
          text: JSON.stringify({ traceId: trace.id, durationMs: trace.durationMs, spansCount: trace.spans.length }),
        },
        redirectURL: '',
        headersSize: -1,
        bodySize: -1,
      },
      cache: {},
      timings: {
        blocked: 0,
        dns: -1,
        connect: -1,
        send: 0,
        wait: time,
        receive: 0,
        ssl: -1,
      },
      serverIPAddress: http?.clientIp || '127.0.0.1',
      comment: `Generated by TraceLens. RootSpan: ${trace.rootSpanId}`,
    },
  ];

  return {
    log: {
      version: '1.2',
      creator: {
        name: 'TraceLens',
        version: '0.1.0',
        comment: 'Zero-lock-in Local Distributed Tracing',
      },
      pages: [
        {
          startedDateTime,
          id: `page_${trace.id}`,
          title: trace.name,
          pageTimings: {
            onContentLoad: -1,
            onLoad: time,
          },
        },
      ],
      entries,
    },
  };
}

/**
 * Sinh cURL command từ thông tin HTTP của Trace
 */
export function toCurlCommand(trace: TraceRecord): string {
  const http = trace.http;
  if (!http) {
    return `# Trace ${trace.id} has no HTTP metadata`;
  }

  const url = http.url || `http://localhost:3000${http.path || '/'}`;
  const parts = [`curl -X ${http.method} "${url}"`];

  if (http.headers) {
    for (const [key, val] of Object.entries(http.headers)) {
      if (['host', 'content-length'].includes(key.toLowerCase())) continue;
      parts.push(`  -H "${key}: ${val}"`);
    }
  }

  if (http.body && ['POST', 'PUT', 'PATCH'].includes(http.method)) {
    const rawBody = typeof http.body === 'string' ? http.body : JSON.stringify(http.body);
    parts.push(`  -d '${rawBody}'`);
  }

  return parts.join(' \\\n');
}

